export const filterApartments = ({ etap, rooms, floor, area, status, stage, limit } = {}) => {
  let result = allApartments;

  if (etap) result = result.filter((a) => a.etap === `etap${etap}`);
  if (stage && !etap) result = result.filter((a) => a.etap === stage);
  if (rooms) result = result.filter((a) => a.liczba_pokoi === parseInt(rooms, 10));
  if (floor !== undefined && floor !== null && floor !== "")
    result = result.filter((a) => a.kondygnacja === parseInt(floor, 10));
  if (area) {
    const ranges = {
      "35-45": [35, 45],
      "45-55": [45, 55],
      "55-65": [55, 65],
      "65-75": [65, 75],
      "75+":   [75, Infinity],
    };
    const [min, max] = ranges[area] || [];
    if (min !== undefined) result = result.filter((a) => a.powierzchnia >= min);
    if (max !== Infinity && max !== undefined) result = result.filter((a) => a.powierzchnia <= max);
  }
  if (status) result = result.filter((a) => a.dostepnosc === status);
  if (limit) result = result.slice(0, parseInt(limit, 10));

  return result;
};
